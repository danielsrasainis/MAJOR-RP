# MAJOR RP build step: open Shared/majorrp-models/*.sealed with the private key from the
# MAJORRP_MODELS_PRIVATE_KEY environment variable (GitHub secret), pack all models into
# MTA/models/models.mrp with a fresh random AES-256 key, and write that key into a generated
# client header. Every build gets its own key, so the key never appears in the public repo.
# Without the secret (forks, pull requests) the build still works, just without built-in models.
import glob, io, os, struct, sys, zipfile
from cryptography.hazmat.primitives import hashes, padding as sympad, serialization
from cryptography.hazmat.primitives.asymmetric import padding
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = os.path.join(ROOT, "Client", "mods", "deathmatch", "logic", "majorrp_models_key.h")
OUT = os.path.join(ROOT, "Shared", "data", "MTA San Andreas", "MTA", "models", "models.mrp")

def write_header(key):
    mask = os.urandom(32)
    a = ", ".join("0x%02x" % (k ^ m) for k, m in zip(key, mask)) if key else ""
    b = ", ".join("0x%02x" % m for m in mask) if key else ""
    with open(HEADER, "w") as f:
        f.write("// Generated by utils/majorrp_pack_models.py at build time. Do not commit.\n#pragma once\n")
        f.write("#define MAJORRP_MODELS_HAVE_KEY %d\n" % (1 if key else 0))
        f.write("static const unsigned char g_MajorRpModelsKeyA[32] = {%s};\n" % (a or "0"))
        f.write("static const unsigned char g_MajorRpModelsKeyB[32] = {%s};\n" % (b or "0"))

pem = os.environ.get("MAJORRP_MODELS_PRIVATE_KEY", "").strip()
sealed = sorted(glob.glob(os.path.join(ROOT, "Shared", "majorrp-models", "*.sealed")))
if not pem or not sealed:
    print("majorrp_pack_models: %s, building without built-in models" % ("no private key secret" if not pem else "no sealed models"))
    write_header(None)
    sys.exit(0)

priv = serialization.load_pem_private_key(pem.encode(), password=None)
entries, lists = {}, []
for path in sealed:
    d = open(path, "rb").read()
    assert d[:5] == b"MRPS1", path
    n = struct.unpack("<H", d[5:7])[0]
    key = priv.decrypt(d[7:7 + n], padding.OAEP(mgf=padding.MGF1(hashes.SHA256()), algorithm=hashes.SHA256(), label=None))
    z = zipfile.ZipFile(io.BytesIO(AESGCM(key).decrypt(d[7 + n:19 + n], d[19 + n:], None)))
    for name in z.namelist():
        if name.lower() == "models.txt":
            lists.append(z.read(name).decode("utf-8", "replace"))
        else:
            entries[name.lower()] = z.read(name)
    print("opened", os.path.basename(path), z.namelist())

payload = io.BytesIO()
def add(name, data):
    nb = name.encode()
    payload.write(struct.pack("<I", len(nb)) + nb + struct.pack("<I", len(data)) + data)
add("models.txt", "\n".join(lists).encode())
for name, data in sorted(entries.items()):
    add(name, data)

key, iv = os.urandom(32), os.urandom(16)
p = sympad.PKCS7(128).padder()
plain = p.update(payload.getvalue()) + p.finalize()
enc = Cipher(algorithms.AES(key), modes.CBC(iv)).encryptor()
os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, "wb") as f:
    f.write(b"MRPK1" + iv + enc.update(plain) + enc.finalize())
write_header(key)
print("majorrp_pack_models: packed %d files into %s" % (len(entries), OUT))
